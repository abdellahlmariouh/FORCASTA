import pandas as pd


def generate_calendar_features(df, date_col="Date"):
    """Extracts calendar attributes from the Date column."""
    df_feat = df.copy()

    # Ensure Date column is available
    if date_col not in df_feat.columns:
        df_feat[date_col] = df_feat.index

    df_feat["Year"] = df_feat[date_col].dt.year
    df_feat["Month"] = df_feat[date_col].dt.month
    df_feat["Quarter"] = df_feat[date_col].dt.quarter
    df_feat["DayOfWeek"] = df_feat[date_col].dt.dayofweek
    df_feat["DayOfYear"] = df_feat[date_col].dt.dayofyear
    df_feat["IsWeekend"] = df_feat["DayOfWeek"].isin([5, 6]).astype(int)

    return df_feat


def generate_lag_rolling_features(
    df, sales_col="Sales", lags=[1, 2, 3], rolling_windows=[3, 6]
):
    """Generates lag features and rolling statistics."""
    df_feat = df.copy()

    # Lag Features
    for lag in lags:
        df_feat[f"{sales_col}_Lag_{lag}"] = df_feat[sales_col].shift(lag)

    # Rolling Features
    for window in rolling_windows:
        df_feat[f"{sales_col}_RollingMean_{window}"] = (
            df_feat[sales_col].rolling(window=window).mean()
        )
        df_feat[f"{sales_col}_RollingStd_{window}"] = (
            df_feat[sales_col].rolling(window=window).std()
        )

    # Drop NaNs generated by shifting/rolling (to prevent issues with ML models)
    df_feat.dropna(inplace=True)

    return df_feat


def engineer_all_features(
    df, date_col="Date", sales_col="Sales", lags=[1, 2, 3], rolling_windows=[3, 6]
):
    """Runs all feature engineering steps sequentially."""
    df_cal = generate_calendar_features(df, date_col)
    df_final = generate_lag_rolling_features(df_cal, sales_col, lags, rolling_windows)
    return df_final
